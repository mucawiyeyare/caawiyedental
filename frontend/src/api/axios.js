import axios from 'axios';

const api = axios.create({
  baseURL: import.meta.env.VITE_API_URL || '/api',
  headers: {
    'Content-Type': 'application/json'
  }
});

// Attach JWT token to requests
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('sodmas_token') || localStorage.getItem('dentalhub_token') || localStorage.getItem('snab_dental_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Global response interceptor for 401 & 403 handling
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      localStorage.removeItem('sodmas_token');
      localStorage.removeItem('sodmas_user');
      localStorage.removeItem('dentalhub_token');
      localStorage.removeItem('dentalhub_user');
      localStorage.removeItem('snab_dental_token');
      localStorage.removeItem('snab_dental_user');
      if (window.location.pathname !== '/login') {
        window.location.href = '/login';
      }
    }
    return Promise.reject(error);
  }
);

export default api;
